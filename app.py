def parse_ci(s: str):
    """'[-0.0106, -0.0068]' -> (-0.0106, -0.0068)"""
    nums = re.findall(r"[-+]?\d*\.\d+|[-+]?\d+", str(s))
    return float(nums[0]), float(nums[1])


def tidy(df: pd.DataFrame) -> pd.DataFrame:
    """Round numbers for display; show p-values as '<0.001' where appropriate."""
    out = df.copy()
    for c in out.columns:
        if not pd.api.types.is_float_dtype(out[c]):
            continue
        if re.search(r"(^p_|_p$|_p_|p_value|DeLong|Jarque)", c):
            out[c] = out[c].map(lambda v: "<0.001" if pd.notna(v) and v < 0.001 else (f"{v:.3f}" if pd.notna(v) else ""))
        else:
            out[c] = out[c].round(4)
    return out


def gains_vs_baseline(df: pd.DataFrame, baseline: str = "A") -> pd.DataFrame:
    """Incremental gains of every configuration over the baseline, per checkpoint,
    for whichever of ROC-AUC, PR-AUC, F1 and recall are present. This is the core
    of the ablation framework and is reused by the 'Apply the framework' tab."""
    cols = [c for c in ["roc_auc", "pr_auc", "f1", "recall"] if c in df.columns]
    rows = []
    for cp, cdf in df.groupby("checkpoint"):
        base = cdf[cdf["model"] == baseline]
        if base.empty:
            continue
        for _, r in cdf[cdf["model"] != baseline].iterrows():
            row = {"checkpoint": cp, "model": r["model"]}
            for c in cols:
                g = round(float(r[c]) - float(base[c].iloc[0]), 4)
                row[f"d_{c}"] = g
                row[f"band_{c}"] = classify_gain(g)
            row["no_meaningful_gain"] = all(row[f"d_{c}"] < MEANINGFUL for c in cols)
            if "behavioural_shap_share" in df.columns and pd.notna(r.get("behavioural_shap_share")):
                row["below_shap_threshold"] = float(r["behavioural_shap_share"]) < SHAP_THRESHOLD
                row["redundant"] = row["no_meaningful_gain"] and row["below_shap_threshold"]
            rows.append(row)
    return pd.DataFrame(rows)


