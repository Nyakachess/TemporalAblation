def config_hue(m):
    if m == "A":
        return COLOURS["A"]
    behavioural = m[2:] if m.startswith("A+") else m
    if "B1" in behavioural and "B2" in behavioural:
        return COMBINED
    if "B2" in behavioural:
        return COLOURS["B2"]
    return COLOURS["B1"]


def standalone_chart(seven: pd.DataFrame, metric: str):
    d = seven[seven["Model"].isin(["A", "B1", "B2"])].copy()
    order = ["A", "B1", "B2"]
    return (
        alt.Chart(d)
        .mark_bar(size=26, cornerRadiusTopLeft=4, cornerRadiusTopRight=4)
        .encode(
            x=alt.X("Checkpoint:N", title=None),
            xOffset=alt.XOffset("Model:N", sort=order),
            y=alt.Y(f"{metric}:Q", title=METRICS.get(metric, metric), scale=alt.Scale(domain=[0, 1])),
            color=alt.Color("Model:N", sort=order, title="Block",
                            scale=alt.Scale(domain=order, range=[COLOURS[o] for o in order])),
            tooltip=["Checkpoint", "Model", alt.Tooltip(f"{metric}:Q", format=".3f")],
        )
        .properties(height=300)
    )


def gains_chart(d: pd.DataFrame, ytitle: str):
    """d: Checkpoint, Configuration, mean, lo, hi"""
    order = ["A+B1", "A+B2", "A+B1+B2"]
    lo = min(d["lo"].min(), 0) - 0.005
    hi = max(d["hi"].max(), MEANINGFUL) + 0.005
    base = alt.Chart(d).encode(
        x=alt.X("Checkpoint:N", title=None),
        xOffset=alt.XOffset("Configuration:N", sort=order),
        color=alt.Color("Configuration:N", sort=order, title="Configuration",
                        scale=alt.Scale(domain=order, range=[config_hue(o) for o in order])),
    )
    bars = base.mark_bar(size=22, cornerRadius=4).encode(
        y=alt.Y("mean:Q", title=ytitle, scale=alt.Scale(domain=[lo, hi])),
        tooltip=["Checkpoint", "Configuration", alt.Tooltip("mean:Q", format="+.4f", title="gain"),
                 alt.Tooltip("lo:Q", format="+.4f"), alt.Tooltip("hi:Q", format="+.4f")],
    )
    err = base.mark_rule(strokeWidth=2, color=INK).encode(y="lo:Q", y2="hi:Q")
    zero = alt.Chart(pd.DataFrame({"y": [0]})).mark_rule(color=MUTED).encode(y="y:Q")
    marginal = alt.Chart(pd.DataFrame({"y": [0.01]})).mark_rule(strokeDash=[5, 4], color=MUTED).encode(y="y:Q")
    meaningful = alt.Chart(pd.DataFrame({"y": [MEANINGFUL]})).mark_rule(strokeDash=[2, 3], color=INK).encode(y="y:Q")
    labels = alt.Chart(pd.DataFrame({"y": [0.0105, 0.0205], "t": ["marginal (0.01)", "meaningful (0.02)"]})).mark_text(
        align="left", x=5, dy=-6, color=MUTED, fontSize=11).encode(y="y:Q", text="t:N")
    return (bars + err + zero + marginal + meaningful + labels).properties(height=340)


def shap_chart(shap_b: pd.DataFrame):
    d = shap_b.melt(id_vars="Checkpoint", value_vars=["Share_A", "Share_B1", "Share_B2"],
                    var_name="block", value_name="share")
    d["block"] = d["block"].str.replace("Share_", "")
    d["pct"] = (d["share"] * 100).round(2)
    order = ["A", "B1", "B2"]
    lines = (
        alt.Chart(d)
        .mark_line(strokeWidth=2, point=alt.OverlayMarkDef(size=80, filled=True))
        .encode(
            x=alt.X("Checkpoint:N", title=None),
            y=alt.Y("pct:Q", title="Share of mean |SHAP| (%)", scale=alt.Scale(domain=[0, 100])),
            color=alt.Color("block:N", sort=order, title="Block",
                            scale=alt.Scale(domain=order, range=[COLOURS[o] for o in order])),
            tooltip=["Checkpoint", "block", "pct"],
        )
    )
    threshold = alt.Chart(pd.DataFrame({"y": [SHAP_THRESHOLD * 100]})).mark_rule(
        strokeDash=[2, 3], color=INK).encode(y="y:Q")
    labels = (
        alt.Chart(d[d["Checkpoint"] == "Q3"])
        .mark_text(align="left", dx=10, fontSize=12, color=INK)
        .encode(x=alt.X("Checkpoint:N"), y="pct:Q", text=alt.Text("pct:Q", format=".1f"))
    )
    return (lines + threshold + labels).properties(height=320)


