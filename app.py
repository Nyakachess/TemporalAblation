def classify_gain(gain: float) -> str:
    """Classify an incremental held-out gain against the pre-specified bands."""
    if gain >= 0.05:
        return "strong"
    if gain >= 0.02:
        return "meaningful"
    if gain >= 0.01:
        return "marginal"
    return "negligible"


